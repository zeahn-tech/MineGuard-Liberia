#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Prepares the existing mining glossary (src/data/safety-reference.ts) as DRAFT rows of
// public_content (migration 0051). It PUBLISHES NOTHING: every row is inserted as a draft marked
// "no qualified sign-off recorded". Ministry reviewers then review, approve and publish each term
// through the normal lifecycle (four-eyes, written note, accuracy/completeness/confidentiality
// checks). English only: no translation is invented.
//
//   node scripts/gen-public-glossary-seed.mjs            # writes supabase/seeds/public_glossary_drafts.sql
//   node scripts/gen-public-glossary-seed.mjs --check    # exits 1 if the committed file is stale
// ---------------------------------------------------------------------------
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "src", "data", "safety-reference.ts"), "utf8");
const out = join(root, "supabase", "seeds", "public_glossary_drafts.sql");

const start = src.indexOf("export const GLOSSARY");
const arrStart = src.indexOf("[", src.indexOf("=", start));
const arrEnd = src.indexOf("\n];", arrStart) + 2;
const entries = JSON.parse(src.slice(arrStart, arrEnd));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const slugOf = (id, term) =>
  String(id).replace(/^ref:glossary:/, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") ||
  term.toLowerCase().replace(/[^a-z0-9]+/g, "-");
const SOURCE = "MineGuard field app reference content (data.js); no qualified sign-off recorded";

const seen = new Set();
const rows = entries.map((e) => {
  const slug = slugOf(e.id, e.term);
  if (seen.has(slug)) throw new Error(`duplicate slug ${slug}`);
  seen.add(slug);
  return { slug, term: e.term, category: e.category, body: e.definition };
});

const lines = [
  "-- ===========================================================================",
  "-- GENERATED by scripts/gen-public-glossary-seed.mjs — do not edit by hand.",
  `-- ${rows.length} glossary terms prepared as DRAFTS of public_content (migration 0051).`,
  "-- NOTHING IS PUBLISHED by this file. Run once as the project owner (SQL editor) AFTER 0051;",
  "-- re-running is harmless (existing rows are left alone). Terms become public only when Ministry",
  "-- reviewers approve and an administrator publishes each one in the app.",
  "-- ===========================================================================",
  "begin;",
  "",
];
for (const r of rows) {
  lines.push(
    `insert into public.public_content (kind, slug, language, title, body, category, status, source)`,
    `values ('glossary_term', ${q(r.slug)}, 'en', ${q(r.term)}, ${q(r.body)}, ${q(r.category)}, 'draft', ${q(SOURCE)})`,
    `on conflict (kind, slug, language, version) do nothing;`,
  );
}
lines.push(
  "",
  "-- one provenance event per imported draft",
  "insert into public.public_content_events (content_id, action, to_status, actor_id, note)",
  "select c.id, 'import', 'draft', null, 'Imported as a draft from the MineGuard field app reference content; not reviewed.'",
  "  from public.public_content c",
  " where c.kind = 'glossary_term' and c.version = 1 and c.status = 'draft' and c.author_id is null",
  "   and not exists (select 1 from public.public_content_events e where e.content_id = c.id);",
  "",
  "commit;",
  "",
);
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("supabase/seeds/public_glossary_drafts.sql is stale — run: node scripts/gen-public-glossary-seed.mjs");
    process.exit(1);
  }
  console.log(`up to date (${rows.length} terms)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${rows.length} terms)`);
}
